"""PostgreSQL DDL generation from a normalized blueprint (deterministic).

Every generated table is tenant-scoped and protected by FORCE RLS.
Identifiers come from ``normalize_blueprint`` (strict allowlist) and are quoted anyway.
"""
from __future__ import annotations

PG_TYPES = {
    "text": "TEXT", "integer": "INTEGER", "float": "DOUBLE PRECISION", "boolean": "BOOLEAN",
    "timestamp": "TIMESTAMPTZ", "date": "DATE", "uuid": "UUID", "jsonb": "JSONB",
    "email": "VARCHAR(320)", "ref": "UUID",
}


def _q(ident: str) -> str:
    return '"' + ident.replace('"', '""') + '"'


def column_type(f: dict) -> str:
    if f["type"] == "text" and f.get("max_length"):
        return f"VARCHAR({int(f['max_length'])})"
    return PG_TYPES[f["type"]]


def generate_ddl(blueprint: dict) -> str:
    """``blueprint`` must be normalized (see packages.blueprint.schema.normalize_blueprint)."""
    tables = {e["name"]: e["table"] for e in blueprint["entities"]}
    out = [
        f"-- Generated by NexusSaaS for {blueprint['name']} v{blueprint['version']}",
        "-- Tenant isolation: set app.tenant_id per transaction (SET LOCAL / set_config).",
        "BEGIN;",
        "CREATE EXTENSION IF NOT EXISTS pgcrypto;",
        "",
    ]
    fks, indexes = [], []
    for e in blueprint["entities"]:
        t = e["table"]
        cols = [
            "  id UUID PRIMARY KEY DEFAULT gen_random_uuid()",
            "  tenant_id UUID NOT NULL",
        ]
        for f in e["fields"]:
            col = f"  {_q(f['name'])} {column_type(f)}"
            if f["required"] and f["type"] != "ref":
                col += " NOT NULL"
            cols.append(col)
        cols += ["  created_at TIMESTAMPTZ NOT NULL DEFAULT now()",
                 "  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()"]
        for f in e["fields"]:
            if f["unique"]:
                cname = "uq_" + t + "_" + f["name"]
                cols.append(f"  CONSTRAINT {_q(cname)} UNIQUE (tenant_id, {_q(f['name'])})")
        out.append(f"CREATE TABLE {_q(t)} (")
        out.append(",\n".join(cols))
        out.append(");")
        indexes.append(f"CREATE INDEX {_q('ix_' + t + '_tenant')} ON {_q(t)} (tenant_id, created_at);")
        for f in e["fields"]:
            if f["type"] == "ref":
                target = tables[f["ref"]]
                fk_name = "fk_" + t + "_" + f["name"]
                fks.append(f"ALTER TABLE {_q(t)} ADD CONSTRAINT {_q(fk_name)} "
                           f"FOREIGN KEY ({_q(f['name'])}) REFERENCES {_q(target)} (id) ON DELETE SET NULL;")
                ix_name = "ix_" + t + "_" + f["name"]
                indexes.append(f"CREATE INDEX {_q(ix_name)} ON {_q(t)} ({_q(f['name'])});")
        out += [
            f"ALTER TABLE {_q(t)} ENABLE ROW LEVEL SECURITY;",
            f"ALTER TABLE {_q(t)} FORCE ROW LEVEL SECURITY;",
            f"CREATE POLICY tenant_isolation ON {_q(t)}",
            "  USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)",
            "  WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid);",
            "",
        ]
    out += fks + indexes + ["", "COMMIT;", ""]
    return "\n".join(out)
